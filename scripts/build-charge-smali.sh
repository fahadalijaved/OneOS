#!/bin/sh
# Regenerate switcher/patches/OneOSChargePower.smali and OneOSMiCharge.smali, the helpers patches/battery_charge_power.py
# and patches/miui_quick_charge.py put into the guest's services.jar and miui-services.jar, from its Java source (the source of truth). android.hardware.health.HealthInfo is not in
# the SDK's android.jar: the source compiles against a stub of the fields it uses (not part of the output).
# Same steps as scripts/build-abi-smali.sh.
#
# Usage: scripts/build-charge-smali.sh   (APKTOOL=<apktool jar> to override)
set -eu
cd "$(dirname "$0")/.."
sdk=${ANDROID_HOME:?Set ANDROID_HOME to the Android SDK}
javac=${JAVA_HOME:+$JAVA_HOME/bin/}javac
jar=$(find "$sdk/platforms" -name android.jar | sort -V | tail -1)
d8=$(find "$sdk/build-tools" -name d8 | sort -V | tail -1)
apktool=${APKTOOL:-$(ls mysticgsi/tools/apktool/*.jar 2>/dev/null | head -1)}
[ -n "$jar" ] && [ -n "$d8" ] && [ -n "$apktool" ]
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM
mkdir -p "$tmp/stub/android/hardware/health" "$tmp/stubcls"
cat > "$tmp/stub/android/hardware/health/HealthInfo.java" <<'STUB'
package android.hardware.health;
public class HealthInfo {
    public boolean chargerAcOnline;
    public boolean chargerUsbOnline;
    public boolean chargerWirelessOnline;
    public boolean chargerDockOnline;
    public int maxChargingCurrentMicroamps;
    public int maxChargingVoltageMicrovolts;
}
STUB
"$javac" --release 17 -classpath "$jar" -d "$tmp/stubcls" "$tmp/stub/android/hardware/health/HealthInfo.java"
for spec in com/android/server/OneOSChargePower com/android/server/OneOSMiCharge; do
    name=$(basename "$spec")
    src=switcher/patches/$name.java
    out=switcher/patches/$name.smali
    rm -rf "$tmp/cls" "$tmp/dex" "$tmp/src" "$tmp/helper.jar"; mkdir "$tmp/cls" "$tmp/dex"
    "$javac" --release 17 -Xlint:all -Werror -classpath "$jar:$tmp/stubcls" -d "$tmp/cls" "$src"
    [ "$(find "$tmp/cls" -name '*.class' | wc -l)" = 1 ] || { echo "$src must stay one class (no inner classes or lambdas)" >&2; exit 1; }
    "$d8" --release --min-api 31 --lib "$jar" --classpath "$tmp/stubcls" --output "$tmp/dex" "$tmp/cls/$spec.class"
    (cd "$tmp/dex" && python3 -c 'import zipfile; z = zipfile.ZipFile("../helper.jar", "w", zipfile.ZIP_STORED); z.write("classes.dex"); z.close()')
    java -jar "$apktool" d -q -f -r -o "$tmp/src" "$tmp/helper.jar"
    got="$tmp/src/smali/$spec.smali"
    [ -f "$got" ]
    if grep -q -E 'invoke-custom|invoke-polymorphic|const-method-handle' "$got"; then
        echo "$src compiles to instructions the patched jars do not use" >&2; exit 1
    fi
    sum=$(sha256sum "$src" | cut -d' ' -f1)
    {
        sed -n '1,/^\.source /p' "$got"
        echo
        echo "# OneOS: a Samsung charger in the guest ($name). Generated by scripts/build-charge-smali.sh"
        echo "# from $src (sha256 $sum); edit the Java, not this file."
        sed -n '/^\.source /,$p' "$got" | sed 1d
    } > "$out"
    echo "$out from $src"
done
