#!/bin/sh
# Regenerate switcher/patches/OneOSInstalldCodes.smali and OneOSOemNetdCodes.smali, the helper
# classes patches/guest_installd_abi.py and patches/guest_oemnetd_abi.py put into the guest's
# services.jar, from their Java sources (the source of truth). The smali is checked in so the
# overlay build needs no compiler, and carries the source's hash. Same steps as
# scripts/build-udfps-smali.sh.
#
# Usage: scripts/build-abi-smali.sh   (APKTOOL=<apktool jar> to override)
set -eu
cd "$(dirname "$0")/.."
sdk=${ANDROID_HOME:?Set ANDROID_HOME to the Android SDK}
javac=${JAVA_HOME:+$JAVA_HOME/bin/}javac
jar=$(find "$sdk/platforms" -name android.jar | sort -V | tail -1)
d8=$(find "$sdk/build-tools" -name d8 | sort -V | tail -1)
apktool=${APKTOOL:-$(ls mysticgsi/tools/apktool/*.jar 2>/dev/null | head -1)}
[ -n "$jar" ] && [ -n "$d8" ] && [ -n "$apktool" ]
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM
for spec in com/android/server/pm/OneOSInstalldCodes com/android/server/OneOSOemNetdCodes; do
    name=$(basename "$spec")
    src=switcher/patches/$name.java
    out=switcher/patches/$name.smali
    rm -rf "$tmp/cls" "$tmp/dex" "$tmp/src" "$tmp/helper.jar"
    mkdir "$tmp/cls" "$tmp/dex"
    "$javac" --release 17 -Xlint:all -Werror -classpath "$jar" -d "$tmp/cls" "$src"
    [ "$(find "$tmp/cls" -name '*.class' | wc -l)" = 1 ] || { echo "$src must stay one class (no inner classes or lambdas)" >&2; exit 1; }
    "$d8" --release --min-api 31 --lib "$jar" --output "$tmp/dex" "$tmp/cls/$spec.class"
    (cd "$tmp/dex" && python3 -c 'import zipfile; z = zipfile.ZipFile("../helper.jar", "w", zipfile.ZIP_STORED); z.write("classes.dex"); z.close()')
    java -jar "$apktool" d -q -f -r -o "$tmp/src" "$tmp/helper.jar"
    got="$tmp/src/smali/$spec.smali"
    [ -f "$got" ]
    if grep -q -E 'invoke-custom|invoke-polymorphic|const-method-handle' "$got"; then
        echo "$src compiles to instructions the patched jars do not use" >&2; exit 1
    fi
    grep -q '"@@ONEOS_[A-Z]*_TABLE@@"' "$got" || { echo "$src: the table placeholder is not one const-string" >&2; exit 1; }
    sum=$(sha256sum "$src" | cut -d' ' -f1)
    {
        sed -n '1,/^\.source /p' "$got"
        echo
        echo "# OneOS: this phone's transaction codes ($name). Generated by scripts/build-abi-smali.sh"
        echo "# from $name.java (sha256 $sum);"
        echo "# do not edit, change the Java source and run the script again."
        sed '1,/^\.source /d' "$got"
    } > "$tmp/out.smali"
    mv "$tmp/out.smali" "$out"
    echo "wrote $out"
done
