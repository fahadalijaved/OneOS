#!/bin/sh
# Regenerate switcher/patches/OneOSLift.smali, the helper patches/coloros_lift_wake.py puts into ColorOS's
# OplusGestureUI.apk, from its Java source (the source of truth). Same steps as scripts/build-charge-smali.sh.
#
# Usage: scripts/build-lift-smali.sh   (APKTOOL=<apktool jar> to override)
set -eu
cd "$(dirname "$0")/.."
sdk=${ANDROID_HOME:?Set ANDROID_HOME to the Android SDK}
javac=${JAVA_HOME:+$JAVA_HOME/bin/}javac
jar=$(find "$sdk/platforms" -name android.jar | sort -V | tail -1)
d8=$(find "$sdk/build-tools" -name d8 | sort -V | tail -1)
apktool=${APKTOOL:-$(ls mysticgsi/tools/apktool/*.jar /srv/projects/OneOS/mysticgsi/tools/apktool/*.jar 2>/dev/null | head -1)}
[ -n "$jar" ] && [ -n "$d8" ] && [ -n "$apktool" ]
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM
spec=com/oplus/gesture/server/OneOSLift
src=switcher/patches/OneOSLift.java
out=switcher/patches/OneOSLift.smali
mkdir "$tmp/cls" "$tmp/dex"
"$javac" --release 17 -Xlint:all -Werror -classpath "$jar" -d "$tmp/cls" "$src"
[ "$(find "$tmp/cls" -name '*.class' | wc -l)" = 1 ] || { echo "$src must stay one class (no inner classes or lambdas)" >&2; exit 1; }
"$d8" --release --min-api 31 --lib "$jar" --output "$tmp/dex" "$tmp/cls/$spec.class"
(cd "$tmp/dex" && python3 -c 'import zipfile; z = zipfile.ZipFile("../helper.jar", "w", zipfile.ZIP_STORED); z.write("classes.dex"); z.close()')
java -jar "$apktool" d -q -f -r -o "$tmp/src" "$tmp/helper.jar"
got="$tmp/src/smali/$spec.smali"
[ -f "$got" ]
if grep -q -E 'invoke-custom|invoke-polymorphic|const-method-handle' "$got"; then
    echo "$src compiles to instructions the patched apps do not use" >&2; exit 1
fi
sum=$(sha256sum "$src" | cut -d' ' -f1)
{
    sed -n '1,/^\.source /p' "$got"
    echo
    echo "# OneOS: ColorOS raise to wake on a Galaxy (OneOSLift). Generated by scripts/build-lift-smali.sh"
    echo "# from $src (sha256 $sum); edit the Java, not this file."
    sed -n '/^\.source /,$p' "$got" | sed 1d
} > "$out"
echo "$out from $src"
