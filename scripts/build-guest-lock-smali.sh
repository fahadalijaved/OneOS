#!/bin/sh
# Regenerate switcher/patches/OneOSGuestLock.smali, the helper class that
# patches/guest_local_lock.py puts into the guest's services.jar, from its Java
# source. The Java file is the source of truth (and runs on a desktop JVM in
# scripts/test-guest-local-lock.py); the smali is checked in so the overlay
# build needs no compiler, and carries the source's hash so a stale copy fails
# that test. No signing key or third-party dependency.
#
# Usage: scripts/build-guest-lock-smali.sh   (APKTOOL=<apktool jar> to override)
set -eu
cd "$(dirname "$0")/.."
sdk=${ANDROID_HOME:?Set ANDROID_HOME to the Android SDK}
javac=${JAVA_HOME:+$JAVA_HOME/bin/}javac
jar=$(find "$sdk/platforms" -name android.jar | sort -V | tail -1)
d8=$(find "$sdk/build-tools" -name d8 | sort -V | tail -1)
apktool=${APKTOOL:-$(ls mysticgsi/tools/apktool/*.jar 2>/dev/null | head -1)}
[ -n "$jar" ] && [ -n "$d8" ] && [ -n "$apktool" ]
src=switcher/patches/OneOSGuestLock.java
out=switcher/patches/OneOSGuestLock.smali
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM
mkdir "$tmp/cls" "$tmp/dex"
"$javac" --release 17 -Xlint:all -Werror -d "$tmp/cls" "$src"
[ "$(find "$tmp/cls" -name '*.class' | wc -l)" = 1 ] || { echo "$src must stay one class (no inner classes or lambdas)" >&2; exit 1; }
"$d8" --release --min-api 31 --lib "$jar" --output "$tmp/dex" "$tmp/cls/com/android/server/locksettings/OneOSGuestLock.class"
(cd "$tmp/dex" && zip -q -0 ../helper.jar classes.dex)
java -jar "$apktool" d -q -f -r -o "$tmp/src" "$tmp/helper.jar"
got="$tmp/src/smali/com/android/server/locksettings/OneOSGuestLock.smali"
[ -f "$got" ]
if grep -q -E 'invoke-custom|invoke-polymorphic|const-method-handle' "$got"; then
    echo "$src compiles to instructions the patched jars do not use" >&2; exit 1
fi
sum=$(sha256sum "$src" | cut -d' ' -f1)
{
    sed -n '1,/^\.source /p' "$got"
    echo
    echo "# OneOS: the guest's own screen lock. Generated by scripts/build-guest-lock-smali.sh"
    echo "# from OneOSGuestLock.java (sha256 $sum);"
    echo "# do not edit, change the Java source and run the script again."
    sed '1,/^\.source /d' "$got"
} > "$tmp/out.smali"
mv "$tmp/out.smali" "$out"
echo "wrote $out"
