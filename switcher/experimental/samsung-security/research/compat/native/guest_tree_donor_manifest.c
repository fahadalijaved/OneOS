#include "guest_tree_donor_manifest.h"

#define DONOR_MANIFEST_BYTES 2430550U

extern const unsigned char guest_tree_donor_manifest_bytes[DONOR_MANIFEST_BYTES];

int guest_tree_open_donor_manifest(struct gtm_manifest *manifest) {
    static const unsigned char digest[32] = {
        0x94, 0x8b, 0x4f, 0x84, 0xa8, 0x71, 0x8e, 0x73,
        0x08, 0x6b, 0x57, 0xe2, 0x63, 0xa4, 0x7a, 0xe0,
        0xa0, 0x19, 0x00, 0x49, 0xfa, 0x54, 0xb3, 0xf9,
        0x1d, 0xc6, 0x4f, 0x81, 0xce, 0x92, 0x86, 0x98,
    };
    return gtm_open(guest_tree_donor_manifest_bytes, DONOR_MANIFEST_BYTES, digest, manifest);
}
